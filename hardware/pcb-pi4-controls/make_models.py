"""FreeCADCmd make_models.py. Writes coloured VRML models for the two parts the
KiCad library has no matching model for, from the same dimensions the case
model uses (../enclosure-pi4/dimensions.json):

- LED_5mm_RGB_standoff.wrl: EBOOT 5 mm RGB LED, leads at 2.0 mm pitch, flange
  standing `led_standoff` above the board (computed by the case build, read from
  ../enclosure-pi4/output/layout.json) so the 3D render shows the real height.
- SW_Omron_B3F-4055.wrl: 12 x 12 mm switch, 7.3 mm to the plunger top.

Model frame: footprint origin, z up from the board's top face, mm. KiCad VRML
models are in units of 0.1 inch, so vertices are scaled by 1/2.54.
"""
import json
from pathlib import Path
import FreeCAD as App
import Part
import MeshPart

HERE = Path(__file__).resolve().parent
CASE = HERE.parent / 'enclosure-pi4'
C = json.loads((CASE / 'dimensions.json').read_text())
LAY = json.loads((CASE / 'output' / 'layout.json').read_text())
OUT = HERE / 'libraries' / 'PiControls.3dshapes'
OUT.mkdir(parents=True, exist_ok=True)
V = App.Vector
PCB_T = C['carrier_thickness']


def wrl(path, parts):
    """parts: list of (shape, (r, g, b), transparency)."""
    out = ['#VRML V2.0 utf8', '# generated by make_models.py']
    for shape, color, transp in parts:
        mesh = MeshPart.meshFromShape(Shape=shape, LinearDeflection=.03, AngularDeflection=.2, Relative=False)
        pts, faces = mesh.Topology
        out.append('Shape { appearance Appearance { material Material { diffuseColor %.3f %.3f %.3f specularColor .3 .3 .3 '
                   'shininess .4 transparency %.2f } }' % (*color, transp))
        out.append(' geometry IndexedFaceSet { creaseAngle 0.5 coord Coordinate { point [')
        out.append(','.join('%.4f %.4f %.4f' % (p.x / 2.54, p.y / 2.54, p.z / 2.54) for p in pts))
        out.append('] } coordIndex [' + ','.join('%d,%d,%d,-1' % tuple(f) for f in faces) + '] } }')
    Path(path).write_text('\n'.join(out) + '\n')


# LED: footprint pads along x at -3, -1, 1, 3 (R, +, G, B).
s = LAY['led_standoff_above_pcb']
d, fd, ft, h = C['led_diameter'], C['led_flange_diameter'], C['led_flange_thickness'], C['led_height']
tip = s + h
lens = Part.makeCylinder(d / 2, tip - d / 2 - (s + ft) + .01, V(0, 0, s + ft - .01)).fuse(
    Part.makeSphere(d / 2, V(0, 0, tip - d / 2))).fuse(Part.makeCylinder(fd / 2, ft, V(0, 0, s))).removeSplitter()
# Flat on the flange marks the cathode side on most 5 mm LEDs; not modelled.
leads = Part.makeCompound([Part.makeBox(.5, .5, s + PCB_T + C['led_lead_tail'] + .2, V(x - .25, -.25, -PCB_T - C['led_lead_tail']))
                           for x in (-3, -1, 1, 3)])
wrl(OUT / 'LED_5mm_RGB_standoff.wrl', [(lens, (.92, .94, .97), .35), (leads, (.75, .75, .78), 0)])

# Switch: centred footprint; terminals at (+-6.25, +-2.5), bosses at (0, +-4.5).
sb, sbh = C['switch_body'], C['switch_body_height']
body = Part.makeBox(sb, sb, sbh, V(-sb / 2, -sb / 2, 0))
plunger = Part.makeCylinder(C['switch_plunger_base_diameter'] / 2, C['switch_plunger_base_height'] - sbh + .01, V(0, 0, sbh - .01))
head_h = C['switch_plunger_head_height']
ph = C['switch_plunger_head']
neck = Part.makeCylinder(1.5, C['switch_height'] - head_h - C['switch_plunger_base_height'] + .02, V(0, 0, C['switch_plunger_base_height'] - .01))
head = Part.makeBox(ph, ph, head_h, V(-ph / 2, -ph / 2, C['switch_height'] - head_h))
tw, tt = C['switch_terminal_section']
pins = Part.makeCompound([Part.makeBox(tt, tw, C['switch_terminal_length'] + .3, V(x - tt / 2, y - tw / 2, -C['switch_terminal_length']))
                          for x in (-6.25, 6.25) for y in (-2.5, 2.5)] +
                         [Part.makeCylinder(C['switch_boss_diameter'] / 2, 1.0, V(0, y, -1.0)) for y in (-4.5, 4.5)])
wrl(OUT / 'SW_Omron_B3F-4055.wrl', [(body, (.12, .12, .13), 0), (plunger.fuse(neck).removeSplitter(), (.20, .20, .22), 0),
                                    (head, (.30, .30, .32), 0), (pins, (.78, .78, .80), 0)])
print('MODELS_OK', OUT)
